"""Copy the existing browser artifact under the unified package identity.

This is a text-only packaging step: it does not import or execute plugin code,
start DSH, install dependencies, or run tests. The legacy client stays unchanged.
"""
from hashlib import sha256
from pathlib import Path
import json
import os
import tempfile


def main():
    directory = Path(__file__).resolve().parent
    root = directory.parent.parent
    manifest = json.loads((root / "package.json").read_text(encoding="utf-8"))
    package = manifest["name"]
    if package != "metis-academic-preset":
        raise ValueError("The historic METIS preset package identity must remain unchanged")
    source = directory.parent / "metis-mode" / "client" / "client.js"
    raw = source.read_bytes()
    original = b"  id: 'metis-academic-mode',"
    if raw.count(original) != 1:
        raise ValueError("Expected exactly one legacy client registration; inspect the source before packaging")
    body = raw.replace(original, ("  id: '" + package + "',").encode("utf-8"), 1)
    header = (
        "// Generated by prepare-client.py; edit metis-mode/client/client.js instead.\n"
        f"// Source SHA-256: {sha256(raw).hexdigest()}\n"
    ).encode("utf-8")
    destination = directory / "client.js"
    artifact = header + body
    if not destination.is_file() or destination.read_bytes() != artifact:
        descriptor, temporary = tempfile.mkstemp(prefix=".metis-client-", dir=directory)
        try:
            with os.fdopen(descriptor, "wb") as stream:
                stream.write(artifact)
                stream.flush()
                os.fsync(stream.fileno())
            os.replace(temporary, destination)
        finally:
            Path(temporary).unlink(missing_ok=True)
    print(json.dumps({
        "artifact": str(destination),
        "source": str(source),
        "sourceSha256": sha256(raw).hexdigest(),
        "artifactSha256": sha256(artifact).hexdigest(),
        "bytes": len(artifact),
        "pluginExecution": "not-performed",
        "tests": "not-run",
    }, ensure_ascii=False))


if __name__ == "__main__":
    main()
